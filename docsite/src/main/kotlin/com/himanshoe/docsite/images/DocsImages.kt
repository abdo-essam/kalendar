/**
 * Renders every calendar view to a PNG pair — one light, one dark — for the documentation pages.
 *
 * The pictures are drawn by the real library through [ImageComposeScene], the same headless
 * rasteriser the golden tests use, rather than captured by hand from a running app. That is the whole
 * point of this file: a screenshot pasted into `docs/` is correct exactly once, and then quietly
 * describes a version of the calendar that no longer exists. These are regenerated by the build every
 * time the site is assembled, so a changed signature, a changed default or a changed palette is
 * visible in the documentation on the next build or not at all.
 *
 * Usage: `generateDocsImages <outputDir>`, which the `:docsite:generateDocsImages` task points at
 * `docs/images`.
 */
fun main(args: Array<String>) {
    require(args.size == 1) { "Expected <outputDir>, got ${args.size} argument(s)" }
    val outputDir = File(args[0])
    outputDir.mkdirs()

    val written = shots().flatMap { shot ->
        Theme.entries.map { theme ->
            val png = shot.render(theme)
            val file = File(outputDir, "${shot.name}-${theme.suffix}.png")
            file.writeBytes(png)
            file
        }
    }

    val stale = outputDir
        .listFiles { file -> file.isFile && file.extension == "png" }
        .orEmpty()
        .filterNot { file -> file in written }
    stale.forEach { file -> file.delete() }

    println("Wrote ${written.size} documentation images to ${outputDir.absolutePath}")
}

/**
 * The two palettes a picture is drawn in, matching the two the documentation site can be read in.
 *
 * Both come from [KalendarThemeDefaults] rather than from a palette invented here, so the images show
 * a reader what they will actually get from `lightColors()` and `darkColors()`.
 */
private enum class Theme(val suffix: String, val colors: () -> KalendarColors) {
    Light(suffix = "light", colors = KalendarThemeDefaults::lightColors),
    Dark(suffix = "dark", colors = KalendarThemeDefaults::darkColors),
}

/**
 * One picture: the file it becomes, the frame it is drawn in, and the view that fills it.
 *
 * [width] and [height] are density-independent pixels — the size of the calendar as an app would lay
 * it out. The bitmap comes out [DENSITY] times larger, which is what makes it sharp on a retina
 * display while the page still shows it at its dp size.
 */
private class Shot(
    val name: String,
    val width: Int,
    val height: Int,
    val content: @Composable () -> Unit,
) {
    fun render(theme: Theme): ByteArray {
        val colors = theme.colors()
        return ImageComposeScene(
            width = width * DENSITY,
            height = height * DENSITY,
            density = Density(DENSITY.toFloat()),
        ) {
            ProvideKalendarTimeSource(Demo.timeSource) {
                KalendarTheme(
                    colors = colors,
                    animations = KalendarAnimations(enabled = false),
                ) {
                    Box(modifier = Modifier.fillMaxSize().background(colors.background)) {
                        content()
                    }
                }
            }
        }.use { scene ->
            scene.render(nanoTime = 0L)
            val settled = scene.render(nanoTime = SETTLE_FRAME_NANOS)
            checkNotNull(settled.encodeToData(EncodedImageFormat.PNG)) { "PNG encode failed for $name" }.bytes
        }
    }
}

/**
 * Two rendered frames rather than one.
 *
 * The first frame composes the view and starts whatever it starts — the Schedule views scroll their
 * grid to the morning from a `LaunchedEffect`, which has not run yet when the first frame is drawn.
 * A second frame a simulated second later catches up with all of it, and with animations disabled
 * there is nothing left in flight after that, so the result is stable from run to run.
 */
private const val SETTLE_FRAME_NANOS = 1_000_000_000L

/**
 * How many bitmap pixels one dp becomes. Two, so the pictures survive a retina display: the page
 * shows them at their dp width and the browser has twice the pixels it needs.
 */
private const val DENSITY = 2

private const val GRID_WIDTH = 460
private const val WEEK_HEIGHT = 180
private const val MONTH_HEIGHT = 470
private const val YEAR_HEIGHT = 820
private const val TIMELINE_HEIGHT = 700
private const val SCHEDULE_HEIGHT = 560
private const val SCHEDULE_WEEK_WIDTH = 700
private const val SCHEDULE_WEEK_HEIGHT = 520
private const val AGENDA_HEIGHT = 560

