/*
 * The bare id rather than `alias(libs.plugins.kotlinJvm)`: the root build already puts the Kotlin
 * plugin on the buildscript classpath without a version, and asking for it again *with* one is a
 * configuration failure. The version still comes from the catalog — it is the one the root declares.
 */
plugins {
    kotlin("jvm")
    alias(libs.plugins.composeMultiplatform)
    alias(libs.plugins.compose.compiler)
}

kotlin {
    jvmToolchain(17)
}

dependencies {
    implementation(libs.jetbrains.markdown)

    /*
     * The documentation images are drawn by the real library, headlessly, by this module — see
     * `com.himanshoe.docsite.images.DocsImages`. Compose for Desktop is here for `ImageComposeScene`
     * and the Skia PNG encoder behind it; nothing else in the generator touches Compose.
